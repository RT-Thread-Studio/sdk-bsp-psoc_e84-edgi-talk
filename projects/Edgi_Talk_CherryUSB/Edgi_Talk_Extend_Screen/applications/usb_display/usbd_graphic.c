void usbd_graphic_set_info(uint16_t width, uint16_t height, uint16_t fps, uint8_t format)
{
    g_lcd_res.width = width;
    g_lcd_res.height = height;
    g_lcd_res.fps = fps;
    g_lcd_format = format;
}

void usbd_graphic_set_edid(const uint8_t *edid, uint16_t len)
{
    if ((edid == NULL) || (len == 0))
    {
        return;
    }

    if (len > sizeof(g_edid))
    {
        len = sizeof(g_edid);
    }

    memcpy(g_edid, edid, len);
}

static int graphic_class_interface_request_handler(uint8_t busid, struct usb_setup_packet *setup, uint8_t **data, uint32_t *len)
{
    (void)busid;

    switch (setup->bRequest)
    {
        case 0: /* request lcd resolution */
            (*len) = sizeof(g_lcd_res);
            memcpy((*data), (uint8_t *)&g_lcd_res, (*len));
            break;

        case 1: /* request edid */
            (*len) = sizeof(g_edid);
            memcpy((*data), g_edid, (*len));
            break;

        case 2: /* request lcd format */
            (*len) = 1;
            (*data)[0] = g_lcd_format;
            break;

        default:
            return -1;
    }

    return 0;
}

struct usbd_interface *usbd_graphic_init_intf(struct usbd_interface *intf)
{
    intf->class_interface_handler = NULL;
    intf->class_endpoint_handler = NULL;
    intf->vendor_handler = graphic_class_interface_request_handler;
    intf->notify_handler = NULL;

    return intf;
}
