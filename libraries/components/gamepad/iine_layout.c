/* Identical Report ID 1 layout read from the IINE-1001 (HOGP) and IINE-1003 (BR/EDR). */
static const uint8_t report_descriptor[] = {
    0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01, 0x05, 0x01, 0x09, 0x01,
    0xa1, 0x00, 0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x15, 0x00,
    0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02, 0xc0, 0x05, 0x02,
    0x15, 0x00, 0x26, 0xff, 0x00, 0x09, 0xc4, 0x09, 0xc5, 0x95, 0x02, 0x75,
    0x08, 0x81, 0x02, 0x05, 0x01, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x35,
    0x00, 0x46, 0x3b, 0x01, 0x65, 0x14, 0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
    0x75, 0x04, 0x95, 0x01, 0x81, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x10,
    0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x10, 0x81, 0x02, 0xc0
};

/* Logical 0..7 span 0..315 degrees. The four cardinal presses confirmed
 * orientation, and releasing the D-pad produced the HID null value 15. */
const struct gamepad_hat_position iine_dpad[9] = {
    {0, HID_DPAD_UP},
    {1, HID_DPAD_UP | HID_DPAD_RIGHT},
    {2, HID_DPAD_RIGHT},
    {3, HID_DPAD_RIGHT | HID_DPAD_DOWN},
    {4, HID_DPAD_DOWN},
    {5, HID_DPAD_DOWN | HID_DPAD_LEFT},
    {6, HID_DPAD_LEFT},
    {7, HID_DPAD_LEFT | HID_DPAD_UP},
    {15, 0}
};

bool iine_layout_matches(const uint8_t *map, size_t length)
{
    return map && length == sizeof(report_descriptor) && !memcmp(map, report_descriptor, length);
}
